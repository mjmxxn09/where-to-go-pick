/// [provinceCode] 도 상세 지도 위 좌표. 그 도 값이 없으면 null.
Offset? projectToDetail(String provinceCode, double lat, double lng) {
  final p = detailProjection[provinceCode];
  if (p == null) return null;
  final y = math.log(math.tan(math.pi / 4 + lat * math.pi / 360));
  return Offset(p[0] * lng + p[1] * y + p[2], p[3] * lng + p[4] * y + p[5]);
}
